/** 把一个视角渲染成定义里的一段（★ 追加在 DEFINITION 之后） */
export function renderAngle(a: Angle): string {
  return (
    `\n────────── 你是这个身份下的第「${a.key}」位员工 ──────────\n` +
    `★★ 你和你的同事**职责完全相同**（都是研究员），**只有看问题的角度不同**。\n` +
    `★ 这不是"你只能做这个" —— 你仍然可以做任何研究；\n` +
    `  这是"你**优先**从哪儿切入"，以及"你交产物时**特别**在意什么"。\n\n` +
    a.stance
  );
}
