//
// ══════════════════════════════════════════════════════════════════
// ★★★ 为什么需要这个文件
// ══════════════════════════════════════════════════════════════════
//
// 设计者指出的结构不对称：
//
//     现在：  身份（researcher）= 员工（the researcher）    ← 一个身份 ↔ 一个活人
//     问题：  身份可以支持多个员工，细节不同 ⇒ **不同角度**
//
// ★★ 为什么不能靠"让模型自己分工"（`P3`/`B2`）：
//   **不要指望模型自己分工** —— 它的默认行为是**跟着处境走**。
//   三个员工如果拿一样的定义、一样的处境，它们会**收敛到同一个做法**。
//   ⇒ 角度必须**写在定义里**（不是写在指示里 —— 见下）。
//
// ★★★ 为什么角度进「定义」而不是「指示」：
//   · 角度是**它是谁的一部分**（这个员工一贯怎么看问题）⇒ 进 `role`（会话级）
//   · 处境是**这一轮遇到什么**                ⇒ 进指示（消息）
//   ★ 若把角度写成指示 ⇒ 每轮都要重复说，且**会被处境冲掉**（指示会腐蚀定义）
//
// ══════════════════════════════════════════════════════════════════
// ★★ 一个诚实的限定：**这套角度是我写的，还没被验证过**
//
//   2026-10-19 预实验 K（真模型、找缺陷任务）**重合度 = 1.000** ——
//   三个"不同下手顺序"的员工给出**完全一样**的答案。
//   ★ 归因：那个任务的答案**确定且唯一**，没有角度起作用的空间。
//   ★★ 所以本文件的角度是**重新设计过的**（改"立场/偏好"，不是"步骤"），
//      但**它是否真的产生差异，要靠集群本体跑出来才知道**。
//      ⇒ 这正是"用集群本体直接试"（设计者裁定）而不是另造实验的原因。
// ══════════════════════════════════════════════════════════════════

/**
 * 一个「员工视角」。
 *
 * ★ 同一个身份（researcher）下的**不同员工**，差别只在这里。
 * ★★ 注意**不是性格描述**，是**可执行的研究偏好** ——
 *    写"你很有好奇心"没用（`P3`：指望模型自己分工是错的）；写"你偏好先证伪"才有抓手。
 */
export interface Angle {
  /** 员工号（用于 id 与日志） */
  key: string;
  /** ★ 这个员工一贯的偏好（进定义，不变） */
  stance: string;
}

