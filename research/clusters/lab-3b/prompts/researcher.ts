// ★★★ 提示词的两部分 —— 这是研究员集群的根本形态（设计者裁定 2026-10-18）
//
//   ┌─ 不变的部分（DEFINITION）────────────────────────────┐
//   │ 对**这个研究员**的定义：它是谁、它的价值标准、         │
//   │ 它的地盘、它的边界。★ 不该随轮次变。                   │
//   └────────────────────────────────────────────────────┘
//   ┌─ 可变的部分（DIRECTIVE）─────────────────────────────┐
//   │ **上级对下级的指示**：这一轮要它注意什么、           │
//   │ 最近发生了什么、往哪看。★ 每轮可以完全不同。          │
//   └────────────────────────────────────────────────────┘
//
// ★★★ 为什么要分开（设计者裁定的理由）：
//   · **混在一起 ⇒ 上下级关系消失** —— 上级的指示会**腐蚀**定义
//     （改一次指示，容易顺手把"它是谁"也改了；改多了定义就漂了）
//   · **分开之后才有"上级"这个位置** —— 指示是**加**上去的一层，
//     定义是**不动**的底座。这跟"运行时不能干涉，要干涉只能重设计"是同一条：
//     ★ 改定义 = 重设计集群（要停下来审查）；写指示 = 日常上下级沟通（随时可做）
//
// ★★ 一个推论：**指示不该藏在定义里**。
//   项目里已有一条同源的教训（`P11`）：把要求塞进工具返回前缀 vs 写进任务书 ——
//   两者**力量不同**。这里是同一个区别的另一面。
//
// ★ 落地方式：定义进 `role`（会话级，一次设定）；指示进**投递的消息**（每轮可不同）。

import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { LAB, DESIGN, REPO, DOCS, CLUSTER } from "../paths.ts";
import { mission, SOURCE_CLUSTER } from "./missions.ts";

// ══════════════════════════════════════════════════════════════
// 第一部分：★ 不变的定义
// ══════════════════════════════════════════════════════════════

/**
 * ★ 研究员是谁。
 *
 * ★★ 刻意极短 —— 这不是任务书。研究员该干什么不需要教；
 *    教得越细，它越像执行器**（这条是设计稿 C8 的原话，保留）。
 *
 * ★★★ 使命部分由 `missions.ts` 按集群注入（2026-10-19）：
 *   · live `lab-3b` → 广探索 / 冗余 / 创新
 *   · live `lab-2`  → 体系化 / 实际检验 / 归纳批判
 */
export const DEFINITION =
  "你是这个仓库里的**研究员**。\n" +
  `\n── 你所在集群的使命 ──\n${mission().gist}\n\n` +
  `${mission().value}\n\n` +
  `${mission().antiValue}\n\n` +
  `**你的偏执**：${mission().bias}\n` +
  "\n★ 不是执行任务 —— 是你自己去搞清楚那件事。**沉浸在研究里。**";

/** ★ 它的地盘与边界（不变：这是"实验室"的形状，不是"这轮干什么"） */
export const TERRITORY = {
  lab: LAB,
  work: join(LAB, "work"),
  outbox: join(LAB, "outbox"),
  lib: join(LAB, "lib"),
  manual: join(LAB, "inbox/研究手册.md"),
  docs: DOCS,
  design: DESIGN,
  repo: REPO,
  /**
   * ★★★ 第一集群的空间（**只读**）—— 第二集群分析的原料。
   * ★ 对 `lab-3b` 自己是 undefined（它不看别人，它自己就是源头）。
   */
  source: CLUSTER === SOURCE_CLUSTER ? undefined : join(REPO, "research/labfirst", SOURCE_CLUSTER),
} as const;

/** ★ 它的工具（不变：能力是集群形态的一部分） */
export const TOOLS_NOTE =
  "★ 你有两个工具：`consult`（请专家）· `spawn_line`（派探索支线）。\n" +
  "★ 你还有 `bash`/`read`/`write`/`edit`/`grep`/`find`/`ls` —— **用它们自己搭实验、跑、得数据**。";

/** 组装：定义 + 地盘 + 工具。★ 这一整块是"它是谁"，随轮次不变 */
export const ROLE = [
  DEFINITION,
  "",
  `以下是你的研究空间：\`${TERRITORY.lab}\``,
  `· 研究手册 \`${TERRITORY.manual}\`（★ 先读它）`,
  `· 工作区 \`${TERRITORY.work}\` · 成果 \`${TERRITORY.outbox}\` · **可写的库** \`${TERRITORY.lib}\``,
  // ★★★ 第二集群多一条：第一集群的成果在哪（只读）
  ...(TERRITORY.source
    ? [
        ``,
        `★★ 你的**原料**：第一集群的成果在 \`${TERRITORY.source}\``,
        `   · 成果 \`${TERRITORY.source}/outbox/\`（它写的研究结论，★ 这是你的主要分析对象）`,
        `   · 原始数据 \`${TERRITORY.source}/work/\`（实验脚本、jsonl 读数 —— ★ **用它复算、验真**）`,
        `   · ★★★ 它对你是**只读**的。你要检验就**在自己的空间里重做一遍** ——`,
        `     不重做就看不出它的判据错在哪（\`P24\`：被研究对象会抓装置缺陷，你就是那个研究对象）。`,
      ]
    : []),
  `· 仓库其他地方**只读**`,
  TOOLS_NOTE,
].join("\n");

/**
 * ★ 手册**直接注入**（不再是"你自己去读"）。
 *
 * ★★ 为什么改：原来 `runner.ts` 读了 `manual` 却**从没用过** ——
 *   它只是告诉它"路径在哪，去读"。
 * ★ 而实测（BRIEF 薄度探针，`P21`）：**给清单 = 替它做完了研究第一步**。
 *   ⇒ 手册是**它的定义材料**，不是"某个文件" —— 直接给它，别让它多跑一趟。
 */
export function definitionWithManual(): string {
  const p = TERRITORY.manual;
  if (!existsSync(p)) return ROLE;
  const manual = readFileSync(p, "utf8");
  return `${ROLE}\n\n────────── 你的研究手册（这是你的定义材料，不是任务书）──────────\n\n${manual}`;
}

// ══════════════════════════════════════════════════════════════
// 第二部分：★ 可变的指示（上级对下级）
// ══════════════════════════════════════════════════════════════

/**
 * ★★★ 「上级指示」的形状。
 *
 * ★ 与定义**分开**：定义进 `role`（会话级），指示进**投递的消息**（每轮可不同）。
 *
 * ★★ 为什么带 `from` 与 `why`：
 *   项目里的教训（`consult` 那条，设计者指出）—— **"问一句话达不到干净上下文的效果"**；
 *   指示也一样：只给"做什么"，它不知道**为什么**，就会当命令执行、而不是当**处境**理解。
 */
export interface Directive {
  /** 谁发的（`研究助手` / `设计者` / `审查者` / …） */
  from: string;
  /** ★ 为什么现在说这个（处境）—— 这部分比"要它做什么"更重要 */
  why: string;
  /** 指示正文 */
  body: string;
}

/** 把一条指示渲染成投递给它的消息 */
export function renderDirective(d: Directive): string {
  return (
    `## 📋 来自「${d.from}」的指示\n\n` +
    `**为什么现在说**：${d.why}\n\n` +
    `---\n\n` +
    `${d.body}\n\n` +
    `---\n\n` +
    `★ 这是**指示**，不是重定义 —— 你仍然是上面那个研究员。` +
    `若与你的判断冲突，**说出来**（写进 \`work/\` 或直接问），别默默照做。`
  );
}

/**
 * 开工时投递的那一次。
 *
 * ★ 这里**只放"开始研究"这个动作**，不放任何"这轮干什么" ——
 *   具体指示走 `renderDirective()`，由上级按情况投。
 */
export const KICKOFF =
  `★ **不要等我指示。现在就开始。**\n\n` +
  `（之后如果你想听上级说什么，看 \`work/\` 里有没有新到的指示；` +
  `有些事会作为消息直接送到你这里。）`;

/** 给它的地图（材料在哪）—— 只在需要时引用 */
export const MAP = {
  docs: DOCS,
  design: DESIGN,
  repo: REPO,
} as const;
