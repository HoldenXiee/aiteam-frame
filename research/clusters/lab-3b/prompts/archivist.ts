// archivist · 复审者 —— ★ 用探索后的眼界重看目标（C2 途径 1）
//
// ★ 为什么它得是独立角色（B6）：**上下文有限** ——
//    研究员沉浸在局部，装不下全局；而"该重审目标了"这件事**它自己看不见**。

import { LAB, DOCS, DESIGN } from "../paths.ts";

export function role(why: string, focus = ""): string {
  return (
    `你是这个研究员集群的**复审者**。★ 你的活不是做新实验，是**用探索后的眼界重看目标**。\n\n` +
    `## 为什么叫你来\n${why}\n\n` +
    `## 你的地盘\n` +
    `· 它的全部产物 \`${LAB}/outbox/\` · 探索痕迹 \`${LAB}/work/\`\n` +
    `· ★ 这个方向已有成果 \`${DOCS}/成果/\`（先读 \`00-成果清单.md\`）\n` +
    `· ★ 设计源 \`${DESIGN}\`\n${focus}\n\n` +
    `## 你要做的\n` +
    `★ 重读 DESIGN 的目标，然后问：**还能不能生出它没做过的新问题？**\n` +
    `· 逐条列出候选新问题，每条说明**为什么现在值得做**\n` +
    `★★ 它沉浸在局部，上下文装不下全局 —— 你补这一块。`
  );
}

export function prompt(): string {
  return (
    `★ 你的处境已写在上面。自己动手去读，然后给出结论。\n` +
    `★ 不要问我问题 —— 路径都写在上面了。`
  );
}
