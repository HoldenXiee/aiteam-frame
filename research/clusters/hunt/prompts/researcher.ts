/**
 * ★★★ 「上级指示」的形状。
 *
 * ★ 与定义**分开**：定义进 `role`（会话级），指示进**投递的消息**（每轮可不同）。
 *
 * ★★ 为什么带 `from` 与 `why`：
 *   项目里的教训（`consult` 那条，设计者指出）—— **"问一句话达不到干净上下文的效果"**；
 *   指示也一样：只给"做什么"，它不知道**为什么**，就会当命令执行、而不是当**处境**理解。
 */
export interface Directive {
  /** 谁发的（`研究助手` / `设计者` / `审查者` / …） */
  from: string;
  /** ★ 为什么现在说这个（处境）—— 这部分比"要它做什么"更重要 */
  why: string;
  /** 指示正文 */
  body: string;
}

/** 把一条指示渲染成投递给它的消息 */
export function renderDirective(d: Directive): string {
  return (
    `## 📋 来自「${d.from}」的指示\n\n` +
    `**为什么现在说**：${d.why}\n\n` +
    `---\n\n` +
    `${d.body}\n\n` +
    `---\n\n` +
    `★ 这是**指示**，不是重定义 —— 你仍然是上面那个研究员。` +
    `若与你的判断冲突，**说出来**（写进 \`work/\` 或直接问），别默默照做。`
  );
}

