//
//   ┌─ 不变的部分（DEFINITION）────────────────────────────┐
//   │ 对**这个研究员**的定义：它是谁、它的价值标准、         │
//   │ 它的地盘、它的边界。★ 不该随轮次变。                   │
//   └────────────────────────────────────────────────────┘
//   ┌─ 可变的部分（DIRECTIVE）─────────────────────────────┐
//   │ **上级对下级的指示**：这一轮要它注意什么、           │
//   │ 最近发生了什么、往哪看。★ 每轮可以完全不同。          │
//   └────────────────────────────────────────────────────┘
//
// ★★★ 为什么要分开（设计者裁定的理由）：
//   · **混在一起 ⇒ 上下级关系消失** —— 上级的指示会**腐蚀**定义
//     （改一次指示，容易顺手把"它是谁"也改了；改多了定义就漂了）
//   · **分开之后才有"上级"这个位置** —— 指示是**加**上去的一层，
//     定义是**不动**的底座。这跟"运行时不能干涉，要干涉只能重设计"是同一条：
//     ★ 改定义 = 重设计集群（要停下来审查）；写指示 = 日常上下级沟通（随时可做）
//
// ★★ 一个推论：**指示不该藏在定义里**。
//   项目里已有一条同源的教训（`P11`）：把要求塞进工具返回前缀 vs 写进任务书 ——
//   两者**力量不同**。这里是同一个区别的另一面。
//
// ★ 落地方式：定义进 `role`（会话级，一次设定）；指示进**投递的消息**（每轮可不同）。

