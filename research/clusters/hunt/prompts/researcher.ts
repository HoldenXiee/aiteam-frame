/**
 * ★ 手册**直接注入**（不再是"你自己去读"）。
 *
 * ★★ 为什么改：原来 `runner.ts` 读了 `manual` 却**从没用过** ——
 *   它只是告诉它"路径在哪，去读"。
 * ★ 而实测（BRIEF 薄度探针，`P21`）：**给清单 = 替它做完了研究第一步**。
 *   ⇒ 手册是**它的定义材料**，不是"某个文件" —— 直接给它，别让它多跑一趟。
 */
export function definitionWithManual(): string {
  const p = TERRITORY.manual;
  if (!existsSync(p)) return ROLE;
  const manual = readFileSync(p, "utf8");
  return `${ROLE}\n\n────────── 你的研究手册（这是你的定义材料，不是任务书）──────────\n\n${manual}`;
}

