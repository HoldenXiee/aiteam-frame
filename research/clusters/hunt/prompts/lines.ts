/**
 * ★★★ 把「团队 + 队内角色」渲染成提示词片段（进 `role`）。
 */
export function renderTeam(teamKey: TeamKey, memberKey: string): string {
  const t = TEAMS[teamKey];
  const m = t.members.find((x) => x.key === memberKey) ?? t.members[0]!;
  return (
    `\n\n────────── 你在这本教科书的哪个团队 ──────────\n` +
    `★ 你是 **${t.key}/${m.key}**。你们这个团队的立场是：\n` +
    `★★★ **${t.stance}**\n\n` +
    `【团队的活】\n${t.gist}\n\n` +
    `【★ 队里你的活】\n${m.gist}\n\n` +
    `${t.failure}\n\n` +
    `────────── ★★★ 但这个集群是**争辩制**，不是分工制 ──────────\n` +
    `★ 这本书必须**同时**成立三件事：讲透为什么 · 讲的东西是对的 · 读者能**拿它当工具用**。\n` +
    `★★ 三类人看同一份东西会看到不同的毛病 —— 所以你的立场是对的，别人的也是。\n` +
    `★★★ **有一群「观众」在评判你们**（他们各有自己的想法，见下）。\n` +
    `  ★ **观众最被谁说服，就写谁的观点。**\n` +
    `  ★★ 全体观众（或 9 成）都支持某一方 ⇒ **争辩结束，那一方写进 book**。\n` +
    `⇒ 所以你的目标不是"说服对手"，是**说服观众**。\n` +
    `★ 辩不出谁对时，用 ` + "joint_experiment" + ` **和对手一起设计实验**来判定 ——\n` +
    `  ★★ 单方设计的实验，对手天然不信它的判据。`
  );
}

/**
 * ★★★ 把「观众」渲染成提示词片段 —— 用于观众 agent（它们**不写产物**，只表态）。
 */
export function renderAudience(a: Audience): string {
  return (
    `\n\n────────── ★★★ 你是「观众」，不是研究者 ──────────\n` +
    `★ 你的身份：${a.who}\n\n` +
    `【★ 你怎么判断】\n${a.bias}\n\n` +
    `【★ 你会卡住什么】\n${a.demands}\n\n` +
    `────────── 你该干什么 ──────────\n` +
    `★★ 三个团队（theory / practice / landing）在争同一个问题。\n` +
    `★★★ **你不生产观点。你只回答一个问题：谁最说服了你？**\n` +
    `★ 用 ` + "judge" + ` 工具表一次态：\n` +
    `  · 最被谁说服（theory / practice / landing / **都不够**）\n` +
    `  · **理由**（按你自己的标准说 —— 你就是按上面那套看的）\n` +
    `  · ★ 若"都不够"：缺什么才能说服你（这一条最有价值）\n` +
    `★★ 不要客气。**不认同一个说法是完全有效的表态** ——\n` +
    `  全体观众都支持某一方时争辩才结束，所以**你的不同意见真的很重要**。`
  );
}

