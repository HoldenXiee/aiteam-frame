// ★★★ forge 的第二集群架构 —— 团队 · 争辩 · 观众 · 共识门
//
// ══════════════════════════════════════════════════════════════════
// ★★★ 设计者裁定（2026-10-19，逐字）：
//
//   「第二集群**不强调一定要写新概念**，而是追求：写的东西**描述的准确、有深度**，
//     **可以用作「工具」来分析使用这新生产范式**。」
//
//   「害怕『辩论会不会永远吵不完』可以尝试加一个『**观众**』，
//     最后『观众』**最被说服哪个观点就写哪个观点**。」
//
//   「如果所有『观众』都支持某个观点（或达到 **9 成支持**）就**结束争辩写入 book**。」
//
//   「建议**每个观众的定义也不同，各自都有想法**。」
//
//   「必须要是**多个团队、多个员工，相互争辩、各自有各自的角度**，
//     **最后争辩出一个都认同的结果才能写进 book**。
//     在争辩中，各个团队**可以设计实验，或共同设计实验**来验证。」
// ══════════════════════════════════════════════════════════════════
//
// ──────────────────────────────────────────────────────────────────
// ★★★ 第 4 次修正：我原来把「新概念」当成了成功判据 —— 这是错的
//
//   ★ 我之前的写法：「如果一个新概念都没有 —— 你们只是做了目录。」
//   ★★ 后果：这句话会**逼它造词**。造出来的词看着像体系，实际是**修辞**。
//
//   ★★★ 设计者要的是**不同的东西**：
//     · **准确**：说清这件事到底是什么（不含糊、不做文学化类比）
//     · **有深度**：讲透为什么（机制、因果链、什么条件下反转）
//     · ★★★ **能当工具用**：读者拿它去**分析**自己遇到的集群问题 ⇒ 能判、能选、能算账
//
//   ★ 判据的差别（这是本文件最重要的改动）：
//     ✘ 旧：「你提出了几个新概念？」   ← 可以靠编词刷分
//     ✔ 新：「★**拿你的说法去分析一个新情况，能不能得出别人得不出的结论？**」
//           「★★**读者能不能按你说的做，并自己验一遍？**」
// ──────────────────────────────────────────────────────────────────
//
// ──────────────────────────────────────────────────────────────────
// ★★★ 观众机制：不是"加一个裁判"，是**把"谁说完了"换成"谁说服了人"**
//
//   ★ 问题：三个团队各持立场 ⇒ 谁都说自己那块最重要 ⇒ **永远收敛不了**。
//   ★★ 观众机制的做法：
//     · 观众**不生产观点**，只**评价**（有人写、有人读）
//     · 观众**各有自己的想法**（设计者明确要求）⇒ 不是三个一样的橡皮图章
//     · ★★★ **谁最被说服，就写谁的观点** ⇒ 争辩有了**终点**（不是"达成一致"，是"被说服"）
//     · ★★ 全体观众（或 ≥90%）支持某个观点 ⇒ **结束争辩，写入 book**
//
//   ★ 为什么这能收敛（不是拍脑袋）：
//     三个团队立场对立 ⇒ 它们之间的偏好是**循环的**（A>B>C>A，投票悖论）。
//     ★★ 但**观众有自己的想法** ⇒ 每个观众对三个立场有**独立的评价函数** ⇒
//        "最被说服"是有定义的（argmax）⇒ **不循环**。
// ══════════════════════════════════════════════════════════════════

