export type LineKey = keyof typeof LINES;

/** ★ forge 的默认三条线 */
export const DEFAULT_LINES: LineKey[] = ["theorist", "practitioner", "critic"];

/**
 * ★★★ 把一条线渲染成提示词片段（进 `role`）。
 *
 * ★ 与 hunt 的 `renderAngle()` 形状相同，但**内容是完全不同的三种活** ——
 *   hunt 的三种是"先看什么"，forge 的三种是"干什么"。
 */
export function renderLine(key: LineKey): string {
  const l = LINES[key];
  return (
    `\n\n────────── 你在这本教科书的哪条线上 ──────────\n` +
    `★ 你是**${l.stance}**（\`${l.key}\`）。\n\n` +
    `${l.gist}\n\n` +
    `${l.failure}\n\n` +
    `★★ 这本书必须**同时**成立三件事：讲透为什么（理论）· 讲的东西是对的（实践）· 读者能用。\n` +
    `★ 你只管自己那条线，**别替另外两条线操心** —— 那是他们的活。`
  );
}
