//   · `forge`（**第二集群**）：写教科书 / 实际检验 / 归纳批判
//       —— 把第一集群的散点**变成可教的东西**，并且**亲手检验它**
//
// ★★ 为什么要分开（设计者的判断，逐字）：
//   「一个偏广、创新、冗余，一个偏总结、实际检验、归纳、批判」
//
// ★★★ 这**不是**"初级/高级"的分工 —— 是**两种都要做的事**，而且**互相打架**：
//   · 探索要**发散**：一个线索就值得开一条线，不收敛、不筛选
//   · 体系化要**收敛**：必须说"这条不成立"、"那两条其实是一条"
//   ★ 一个 agent 同时做这两件事 = 它在**自我审查**：
//     过早判"不成立"会杀掉还没长出来的线索；不敢判"不成立"则体系是垃圾场。
//   ⇒ 拆成两个集群，**各自的偏执才成立**。
//
// ★ 依据（本项目已有成果）：
//   · `C7`  它判不了自己的盲区 —— 所以「体系化」这件事**不能在第一集群里做**
//   · `P7`  取交集治不了系统性错误 —— 体系化不是"挑大家都同意的"
//   · `P46/P47` 并集会被霰弹毒化 —— 所以第二集群**必须能批判**，不能只做汇总
//   · `P24` 被研究对象会抓装置缺陷 —— 第二集群做检验时，它会**抓到第一集群的判据缺陷**
//
// ★★ 第二集群**不是**"整理文档的"（设计者明确裁定）：
//   「第二集群的权限一样，也是**需要用实验来检验**体系化的正确性、可行性、局限等等」
//   ⇒ 它有完整的实验能力，**它的结论也要有验证与成本**。

